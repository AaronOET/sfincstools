"""
Remove the files generated by a SFINCS model run.

  sfclr [MODEL_DIR] [--yes] [--post] [--recursive] [--move-to DIR]

  sfclr                         dry run: list what would be removed
  sfclr --yes                   actually delete
  sfclr --post --yes            also delete post-processing products
  sfclr PATH/TO/MODEL --yes     clean another model folder
  sfclr --move-to _old_run -y   move instead of delete
  sfclr D:/runs -r --yes        every model folder below D:/runs

What counts as "generated" (default):
  * sfincs_map.nc, sfincs_his.nc               NetCDF map / history output
  * sfincs_log.txt, sfincs.log, runtimes.txt   run logs written by sfincs.exe
  * sfincs.<time>.rst                          restart output (dtrstout / trstout)
  * zs.dat, zsmax.dat, velmax.dat, tmax.dat, cumprcp.dat, cuminf.dat, qmax.dat,
    t_zsmax.dat, z_volume.dat                  binary output (outputformat = bin)
  * zs.txt, u.txt, v.txt, cumprcp.txt          ascii map output (outputformat = asc)
  * zst.txt, prcp.txt, qt.txt, qdrain.txt      ascii his output
With --post also the products of the view-results notebooks:
  * sfincs_hmax*.tif / *.png, sfincs_*animation*.gif

Not touched: build logs (hydromt.log, build.log), notebooks, scripts, figures not listed
above, and anything in sub-folders unless --recursive is given.

Safety:
  * Any file named in a *.inp in the model folder (mskfile, sbgfile, rstfile, ...)
    is never removed, even if it matches a pattern (e.g. a restart file used as input).
  * A folder without a *.inp file is not treated as a SFINCS model.
"""
import argparse
import fnmatch
import shutil
import sys
from pathlib import Path

RUN_OUTPUTS = [
    # NetCDF
    "sfincs_map.nc", "sfincs_his.nc",
    # logs
    "sfincs_log.txt", "sfincs.log", "runtimes.txt",
    # restart output
    "sfincs.*.rst",
    # binary map / max output
    "zs.dat", "z_volume.dat", "zsmax.dat", "velmax.dat", "tmax.dat",
    "cumprcp.dat", "cuminf.dat", "qmax.dat", "t_zsmax.dat",
    # ascii map output
    "zs.txt", "u.txt", "v.txt", "cumprcp.txt",
    # ascii his output
    "zst.txt", "prcp.txt", "qt.txt", "qdrain.txt",
]

POST_OUTPUTS = [
    "sfincs_hmax*.tif", "sfincs_hmax*.png", "sfincs_*animation*.gif",
]

SKIP_DIRS = {".ipynb_checkpoints", ".git", "__pycache__"}


def read_inp_references(model_dir: Path):
    """All files named as a value in any *.inp of the folder (resolved paths)."""
    refs = set()
    for inp in model_dir.glob("*.inp"):
        try:
            text = inp.read_text(errors="ignore")
        except OSError:
            continue
        for line in text.splitlines():
            s = line.split("!")[0].strip()
            if not s or s.startswith("#") or "=" not in s:
                continue
            key, val = (x.strip() for x in s.split("=", 1))
            if not val or not key.lower().endswith("file"):
                continue
            refs.add((model_dir / val).resolve())
    return refs


def model_dirs(root: Path, recursive: bool):
    """root itself, or with recursive every folder below root that contains a *.inp"""
    if not recursive:
        return [root]
    out = []
    for d in [root] + sorted(p for p in root.rglob("*") if p.is_dir()):
        if any(part in SKIP_DIRS for part in d.relative_to(root).parts):
            continue
        if any(d.glob("*.inp")):
            out.append(d)
    return out


def find_generated(model_dir: Path, post: bool = False):
    """[(file, reason)] of the generated files in model_dir (not recursive)"""
    refs = read_inp_references(model_dir)
    patterns = RUN_OUTPUTS + (POST_OUTPUTS if post else [])
    found = []
    for f in model_dir.iterdir():
        if not f.is_file() or f.resolve() in refs:
            continue
        name = f.name.lower()
        for pat in patterns:
            if fnmatch.fnmatch(name, pat.lower()):
                kind = "post-processing" if pat in POST_OUTPUTS else "run output"
                found.append((f, f"{kind}, {pat}"))
                break
    return sorted(found)


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def build_parser():
    ap = argparse.ArgumentParser(prog="sfclr", description="Remove the files generated by a SFINCS model run.")
    ap.add_argument("model_dir", nargs="?", default=".", type=Path,
                    help="model folder (default: current folder)")
    ap.add_argument("--yes", "-y", action="store_true", help="actually delete (default is dry run)")
    ap.add_argument("--post", action="store_true",
                    help="also remove post-processing products (hmax tif/png, animations)")
    ap.add_argument("--recursive", "-r", action="store_true",
                    help="clean every folder below model_dir that contains a *.inp")
    ap.add_argument("--move-to", metavar="DIR",
                    help="move files into DIR (relative to each model folder) instead of deleting")
    return ap


def main(argv=None):
    args = build_parser().parse_args(argv)

    root = args.model_dir.resolve()
    if not root.is_dir():
        sys.exit(f"Not a folder: {root}")
    if not args.recursive and not any(root.glob("*.inp")):
        sys.exit(f"No *.inp file in {root} - is this a SFINCS model folder? (use -r for sub-folders)")
    dirs = model_dirs(root, args.recursive)
    if not dirs:
        sys.exit(f"No SFINCS model folder (*.inp) found below {root}")

    targets = []                                   # (model_dir, file, why)
    for d in dirs:
        targets += [(d, f, why) for f, why in find_generated(d, args.post)]
    if not targets:
        print("Nothing to clean.")
        return

    total = 0
    current = None
    for d, f, why in targets:
        if d != current:
            print(f"Model folder: {d}")
            current = d
        size = f.stat().st_size
        total += size
        print(f"  {f.name:<32} {human(size):>10}   ({why})")
    print(f"{len(targets)} file(s), {human(total)}")

    if not args.yes:
        print("\nDry run - nothing removed. Re-run with --yes to clean.")
        return

    errors = 0
    for d, f, _ in targets:
        try:
            if args.move_to:
                dest = Path(args.move_to)
                dest = dest if dest.is_absolute() else d / dest
                dest.mkdir(parents=True, exist_ok=True)
                shutil.move(str(f), str(dest / f.name))
            else:
                f.unlink()
        except OSError as e:
            errors += 1
            print(f"  ! could not remove {f}: {e}")
    action = f"moved to {args.move_to}" if args.move_to else "deleted"
    print(f"{len(targets) - errors} file(s) {action}." + (f" {errors} failed." if errors else ""))


if __name__ == "__main__":
    main()
